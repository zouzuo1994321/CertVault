def load_samples(db: Database) -> int:
    """写入示例数据，返回写入条数。"""
    n = 0
    existing = {c["name"] for c in db.certificates()}
    for row in CERTS:
        if row[0] in existing:
            continue
        db.save_certificate({
            "name": row[0], "category": row[1], "number": row[2], "holder": row[3],
            "issuer": row[4], "level": row[5], "issue_date": row[6],
            "expiry_date": row[7], "active": 1, "remark": row[8],
        })
        n += 1
    exists_e = {e["name"] for e in db.exams()}
    for row in EXAMS:
        if row[0] in exists_e:
            continue
        db.save_exam({
            "name": row[0], "category": row[1], "exam_date": row[2],
            "reg_deadline": row[3], "location": row[4], "fee": row[5],
            "state": row[6], "score": row[7], "remark": row[8],
        })
        n += 1
    exists_m = {m["title"] for m in db.materials()}
    for row in MATERIALS:
        if row[0] in exists_m:
            continue
        db.save_material({
            "title": row[0], "category": row[1], "kind": row[2],
            "target": row[3], "note": row[4],
        })
        n += 1
    return n
